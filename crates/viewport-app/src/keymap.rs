use egui::Key;
use viewport_input::Scancode;

/// Maps an `egui::Key` to a Windows PS/2 Scancode (Set 1).
pub fn egui_key_to_scancode(key: Key) -> Option<Scancode> {
    match key {
        Key::Escape => Some(Scancode::ESCAPE),
        Key::Num1 => Some(Scancode::KEY_1),
        Key::Num2 => Some(Scancode::KEY_2),
        Key::Num3 => Some(Scancode::KEY_3),
        Key::Num4 => Some(Scancode::KEY_4),
        Key::Num5 => Some(Scancode::KEY_5),
        Key::Num6 => Some(Scancode::KEY_6),
        Key::Num7 => Some(Scancode::KEY_7),
        Key::Num8 => Some(Scancode::KEY_8),
        Key::Num9 => Some(Scancode::KEY_9),
        Key::Num0 => Some(Scancode::KEY_0),
        Key::Minus => Some(Scancode::MINUS),
        Key::Equals => Some(Scancode::EQUALS),
        Key::Backspace => Some(Scancode::BACKSPACE),
        Key::Tab => Some(Scancode::TAB),

        Key::Q => Some(Scancode::KEY_Q),
        Key::W => Some(Scancode::KEY_W),
        Key::E => Some(Scancode::KEY_E),
        Key::R => Some(Scancode::KEY_R),
        Key::T => Some(Scancode::KEY_T),
        Key::Y => Some(Scancode::KEY_Y),
        Key::U => Some(Scancode::KEY_U),
        Key::I => Some(Scancode::KEY_I),
        Key::O => Some(Scancode::KEY_O),
        Key::P => Some(Scancode::KEY_P),
        Key::OpenBracket => Some(Scancode::LEFT_BRACKET),
        Key::CloseBracket => Some(Scancode::RIGHT_BRACKET),
        Key::Enter => Some(Scancode::ENTER),

        Key::A => Some(Scancode::KEY_A),
        Key::S => Some(Scancode::KEY_S),
        Key::D => Some(Scancode::KEY_D),
        Key::F => Some(Scancode::KEY_F),
        Key::G => Some(Scancode::KEY_G),
        Key::H => Some(Scancode::KEY_H),
        Key::J => Some(Scancode::KEY_J),
        Key::K => Some(Scancode::KEY_K),
        Key::L => Some(Scancode::KEY_L),
        Key::Semicolon => Some(Scancode::SEMICOLON),
        Key::Quote => Some(Scancode::APOSTROPHE),
        Key::Backtick => Some(Scancode::GRAVE),

        Key::Backslash => Some(Scancode::BACKSLASH),
        Key::Z => Some(Scancode::KEY_Z),
        Key::X => Some(Scancode::KEY_X),
        Key::C => Some(Scancode::KEY_C),
        Key::V => Some(Scancode::KEY_V),
        Key::B => Some(Scancode::KEY_B),
        Key::N => Some(Scancode::KEY_N),
        Key::M => Some(Scancode::KEY_M),
        Key::Comma => Some(Scancode::COMMA),
        Key::Period => Some(Scancode::PERIOD),
        Key::Slash => Some(Scancode::SLASH),
        Key::Space => Some(Scancode::SPACE),

        Key::F1 => Some(Scancode::F1),
        Key::F2 => Some(Scancode::F2),
        Key::F3 => Some(Scancode::F3),
        Key::F4 => Some(Scancode::F4),
        Key::F5 => Some(Scancode::F5),
        Key::F6 => Some(Scancode::F6),
        Key::F7 => Some(Scancode::F7),
        Key::F8 => Some(Scancode::F8),
        Key::F9 => Some(Scancode::F9),
        Key::F10 => Some(Scancode::F10),
        Key::F11 => Some(Scancode::F11),
        Key::F12 => Some(Scancode::F12),

        Key::Home => Some(Scancode::HOME),
        Key::End => Some(Scancode::END),
        Key::PageUp => Some(Scancode::PAGE_UP),
        Key::PageDown => Some(Scancode::PAGE_DOWN),
        Key::Insert => Some(Scancode::INSERT),
        Key::Delete => Some(Scancode::DELETE),

        Key::ArrowUp => Some(Scancode::UP_ARROW),
        Key::ArrowDown => Some(Scancode::DOWN_ARROW),
        Key::ArrowLeft => Some(Scancode::LEFT_ARROW),
        Key::ArrowRight => Some(Scancode::RIGHT_ARROW),

        _ => None,
    }
}
